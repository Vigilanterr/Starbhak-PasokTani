import { sql } from 'kysely';
import type { Executor } from '../executor';
import { requireTransaction } from '../executor';
import type { NotificationCategory } from '../db.generated';

// ---------- Conversations ----------

export const CONVERSATION_COLUMNS = [
  'id', 'buyer_id', 'farmer_id', 'last_message_at', 'buyer_last_read_at', 'farmer_last_read_at', 'created_at',
] as const;

/** A conversation is between one buyer and one farmer. Both sides are listed in the row, so either party can see it. */
function partyOfConversation(userId: string) {
  return sql<boolean>`(conversations.buyer_id = ${userId}::uuid or conversations.farmer_id = ${userId}::uuid)`;
}

/**
 * Returns the pair's conversation, creating it on first contact. The unique index on (buyer_id, farmer_id)
 * is the conflict target. A conflict returns no row, so the follow-up select returns the existing one.
 */
export async function getOrCreateConversation(db: Executor, a: { buyerId: string; farmerId: string }) {
  const created = await db.insertInto('conversations')
    .values({ buyer_id: a.buyerId, farmer_id: a.farmerId })
    .onConflict((oc) => oc.columns(['buyer_id', 'farmer_id']).doNothing())
    .returning(CONVERSATION_COLUMNS)
    .executeTakeFirst();
  if (created) return created;
  return db.selectFrom('conversations')
    .select(CONVERSATION_COLUMNS)
    .where('buyer_id', '=', a.buyerId)
    .where('farmer_id', '=', a.farmerId)
    .executeTakeFirstOrThrow();
}

/** One conversation, for a party only. A stranger gets undefined. */
export function findConversationForParty(db: Executor, conversationId: string, userId: string) {
  return db.selectFrom('conversations')
    .select(CONVERSATION_COLUMNS)
    .where('id', '=', conversationId)
    .where(partyOfConversation(userId))
    .executeTakeFirst();
}

/**
 * The user's conversations, most recent activity first. Activity is the last message, or the creation time for a
 * conversation with no messages yet. Keyset on (activity, id); pass the last row's id as afterId.
 */
export function listConversationsForUser(db: Executor, a: { userId: string; afterId: string | null; limit: number }) {
  const activity = sql<Date>`coalesce(conversations.last_message_at, conversations.created_at)`;
  let q = db.selectFrom('conversations')
    .select([...CONVERSATION_COLUMNS, activity.as('activity_at')])
    .where(partyOfConversation(a.userId));
  if (a.afterId) {
    q = q.where(sql<boolean>`(${activity}, conversations.id) < (
      select coalesce(c.last_message_at, c.created_at), c.id from conversations c where c.id = ${a.afterId}::uuid)`);
  }
  return q.orderBy('activity_at', 'desc').orderBy('id', 'desc').limit(a.limit + 1).execute();
}

/**
 * Moves the caller's read marker to now(). The other side's marker is kept. A stranger gets undefined.
 * The CASE is evaluated against the row as it was, so one statement sets only the caller's side.
 */
export function markConversationRead(db: Executor, a: { conversationId: string; userId: string }) {
  return db.updateTable('conversations')
    .set({
      buyer_last_read_at: sql<Date>`case when buyer_id = ${a.userId}::uuid then now() else buyer_last_read_at end`,
      farmer_last_read_at: sql<Date>`case when farmer_id = ${a.userId}::uuid then now() else farmer_last_read_at end`,
    })
    .where('id', '=', a.conversationId)
    .where((eb) => eb.or([eb('buyer_id', '=', a.userId), eb('farmer_id', '=', a.userId)]))
    .returning(CONVERSATION_COLUMNS)
    .executeTakeFirst();
}

// ---------- Messages ----------

export const MESSAGE_COLUMNS = [
  'id', 'conversation_id', 'sender_id', 'client_message_id', 'body', 'attachment_media_id', 'product_id', 'created_at',
] as const;

export interface NewMessage {
  conversationId: string;
  senderId: string;
  /** Generated by the client. The pair (sender_id, client_message_id) is unique, so a resend is a replay. */
  clientMessageId: string;
  body?: string | null;
  attachmentMediaId?: string | null;
  productId?: string | null;
}

function findMessageByClientId(db: Executor, m: { conversationId: string; senderId: string; clientMessageId: string }) {
  return db.selectFrom('messages')
    .select(MESSAGE_COLUMNS)
    .where('conversation_id', '=', m.conversationId)
    .where('sender_id', '=', m.senderId)
    .where('client_message_id', '=', m.clientMessageId)
    .executeTakeFirst();
}

type MessageRow = NonNullable<Awaited<ReturnType<typeof findMessageByClientId>>>;

/**
 * Sends a message and moves the conversation's last_message_at to the message time, in one transaction.
 * Only a party can send: the check is in the INSERT ... SELECT. A resend with the same client_message_id returns
 * the stored row with created: false and writes nothing. Undefined means the sender is not a party.
 * The body or attachment rule is the table's CHECK (chk_message_content), so it fails as a typed error.
 */
export async function insertMessage(db: Executor, m: NewMessage): Promise<{ message: MessageRow; created: boolean } | undefined> {
  requireTransaction(db, 'insertMessage');
  const inserted = await db.insertInto('messages')
    .columns(['conversation_id', 'sender_id', 'client_message_id', 'body', 'attachment_media_id', 'product_id'])
    .expression((eb) => eb.selectFrom('conversations')
      .select([
        'conversations.id as conversation_id',
        sql<string>`${m.senderId}::uuid`.as('sender_id'),
        sql<string>`${m.clientMessageId}::uuid`.as('client_message_id'),
        sql<string | null>`${m.body ?? null}::text`.as('body'),
        sql<string | null>`${m.attachmentMediaId ?? null}::uuid`.as('attachment_media_id'),
        sql<string | null>`${m.productId ?? null}::uuid`.as('product_id'),
      ])
      .where('conversations.id', '=', m.conversationId)
      .where(partyOfConversation(m.senderId)))
    .onConflict((oc) => oc.columns(['sender_id', 'client_message_id']).doNothing())
    .returning(MESSAGE_COLUMNS)
    .executeTakeFirst();

  if (inserted) {
    await db.updateTable('conversations')
      .set({ last_message_at: inserted.created_at })
      .where('id', '=', m.conversationId)
      .execute();
    return { message: inserted, created: true };
  }

  // Conflict or non-party. The lookup is scoped to this sender, so a stranger finds nothing.
  const stored = await findMessageByClientId(db, m);
  return stored ? { message: stored, created: false } : undefined;
}

/**
 * Messages after a cursor, oldest first, for catch-up. This is the SSE Last-Event-ID path: WHERE id > $last.
 * UUIDv7 ids are time-ordered, so id is the keyset. A non-party gets an empty list.
 */
export function listMessagesAfter(db: Executor, a: { conversationId: string; viewerId: string; afterId: string | null; limit: number }) {
  let q = db.selectFrom('messages')
    .select(MESSAGE_COLUMNS)
    .where('conversation_id', 'in', (eb) => eb.selectFrom('conversations')
      .select('id')
      .where('id', '=', a.conversationId)
      .where(partyOfConversation(a.viewerId)));
  if (a.afterId) q = q.where('id', '>', a.afterId);
  return q.orderBy('id', 'asc').limit(a.limit).execute();
}

/**
 * Older messages before a cursor, newest first, for scrolling back. Pass null for the latest page.
 * Fetches limit + 1 so the caller knows another page exists. A non-party gets an empty list.
 */
export function listMessagesBefore(db: Executor, a: { conversationId: string; viewerId: string; beforeId: string | null; limit: number }) {
  let q = db.selectFrom('messages')
    .select(MESSAGE_COLUMNS)
    .where('conversation_id', 'in', (eb) => eb.selectFrom('conversations')
      .select('id')
      .where('id', '=', a.conversationId)
      .where(partyOfConversation(a.viewerId)));
  if (a.beforeId) q = q.where('id', '<', a.beforeId);
  return q.orderBy('id', 'desc').limit(a.limit + 1).execute();
}

/**
 * Messages in the user's conversations that the user has not read: sent by the other party, after that
 * side's read marker. Returned as a string, the way count() comes back from pg.
 */
export async function countUnreadMessages(db: Executor, userId: string): Promise<string> {
  const row = await db.selectFrom('messages')
    .innerJoin('conversations', 'conversations.id', 'messages.conversation_id')
    .select((eb) => eb.fn.countAll<string>().as('unread'))
    .where('messages.sender_id', '<>', userId)
    .where((eb) => eb.or([
      eb.and([
        eb('conversations.buyer_id', '=', userId),
        eb.or([
          eb('conversations.buyer_last_read_at', 'is', null),
          eb('messages.created_at', '>', eb.ref('conversations.buyer_last_read_at')),
        ]),
      ]),
      eb.and([
        eb('conversations.farmer_id', '=', userId),
        eb.or([
          eb('conversations.farmer_last_read_at', 'is', null),
          eb('messages.created_at', '>', eb.ref('conversations.farmer_last_read_at')),
        ]),
      ]),
    ]))
    .executeTakeFirstOrThrow();
  return row.unread;
}

// ---------- Notifications ----------

export const NOTIFICATION_COLUMNS = [
  'id', 'user_id', 'category', 'type', 'title', 'body', 'link', 'data', 'read_at', 'pushed_at', 'created_at',
] as const;

export interface NewNotification {
  userId: string;
  category: NotificationCategory;
  /** e.g. waitlist.schedule_changed, product.back_in_stock */
  type: string;
  title: string;
  body?: string | null;
  /** Frontend path, e.g. /pesanan/<id> */
  link?: string | null;
  data?: Record<string, unknown>;
}

/** Writes notifications for a fan-out in one statement. An empty list writes nothing. */
export async function insertNotifications(db: Executor, rows: NewNotification[]) {
  if (rows.length === 0) return [];
  return db.insertInto('notifications')
    .values(rows.map((r) => ({
      user_id: r.userId,
      category: r.category,
      type: r.type,
      title: r.title,
      body: r.body ?? null,
      link: r.link ?? null,
      data: JSON.stringify(r.data ?? {}),
    })))
    .returning(NOTIFICATION_COLUMNS)
    .execute();
}

/** The user's notifications, newest first. Keyset on (created_at, id). Matches notifications (user_id, created_at). */
export function listNotificationsForUser(db: Executor, a: { userId: string; unreadOnly?: boolean; afterId: string | null; limit: number }) {
  let q = db.selectFrom('notifications').select(NOTIFICATION_COLUMNS).where('user_id', '=', a.userId);
  if (a.unreadOnly) q = q.where('read_at', 'is', null);
  if (a.afterId) q = q.where(sql<boolean>`(created_at, id) < (select created_at, id from notifications where id = ${a.afterId}::uuid)`);
  return q.orderBy('created_at', 'desc').orderBy('id', 'desc').limit(a.limit + 1).execute();
}

/** Unread count for the badge. Uses the partial index notifications (user_id) WHERE read_at IS NULL. */
export async function countUnreadNotifications(db: Executor, userId: string): Promise<string> {
  const row = await db.selectFrom('notifications')
    .select((eb) => eb.fn.countAll<string>().as('unread'))
    .where('user_id', '=', userId)
    .where('read_at', 'is', null)
    .executeTakeFirstOrThrow();
  return row.unread;
}

/** Marks the listed notifications read. Ids that belong to another user, or are already read, are skipped. */
export async function markNotificationsRead(db: Executor, userId: string, ids: string[]) {
  if (ids.length === 0) return [];
  return db.updateTable('notifications')
    .set({ read_at: sql<Date>`now()` })
    .where('user_id', '=', userId)
    .where('id', 'in', ids)
    .where('read_at', 'is', null)
    .returning(['id'])
    .execute();
}

export function markAllNotificationsRead(db: Executor, userId: string) {
  return db.updateTable('notifications')
    .set({ read_at: sql<Date>`now()` })
    .where('user_id', '=', userId)
    .where('read_at', 'is', null)
    .returning(['id'])
    .execute();
}

/** Records that web push went out. Only rows not yet pushed change. An empty list writes nothing. */
export async function markNotificationsPushed(db: Executor, ids: string[]) {
  if (ids.length === 0) return [];
  return db.updateTable('notifications')
    .set({ pushed_at: sql<Date>`now()` })
    .where('id', 'in', ids)
    .where('pushed_at', 'is', null)
    .returning(['id'])
    .execute();
}

// ---------- Outbox ----------

export const OUTBOX_COLUMNS = [
  'id', 'aggregate_type', 'aggregate_id', 'event_type', 'payload', 'created_at', 'available_at',
  'processed_at', 'attempts', 'last_error',
] as const;

export interface NewOutboxEvent {
  aggregateType: string;
  aggregateId: string;
  eventType: string;
  payload: Record<string, unknown>;
}

/**
 * Adds an event to the outbox. It must commit with the business change, so it requires a transaction: outside
 * one, the event would be written alone and the change could still fail.
 */
export async function insertOutboxEvent(db: Executor, e: NewOutboxEvent): Promise<string> {
  requireTransaction(db, 'insertOutboxEvent');
  const row = await db.insertInto('outbox_events')
    .values({
      aggregate_type: e.aggregateType,
      aggregate_id: e.aggregateId,
      event_type: e.eventType,
      payload: JSON.stringify(e.payload),
    })
    .returning(['id'])
    .executeTakeFirstOrThrow();
  return row.id;
}

/**
 * Claims due, unprocessed events for a worker. A single statement: the row lock is held only for the statement,
 * so no transaction is held open while the worker calls Redis or web push. The claim pushes available_at forward by
 * the lease and counts the attempt. A worker that dies leaves the rows to be claimed again after the lease.
 * SKIP LOCKED lets several workers claim in parallel without waiting on each other.
 */
export function claimOutboxEvents(db: Executor, a: { limit: number; leaseSeconds: number }) {
  return db.updateTable('outbox_events')
    .set((eb) => ({
      attempts: eb('attempts', '+', 1),
      available_at: sql<Date>`now() + make_interval(secs => ${a.leaseSeconds})`,
    }))
    .where('id', 'in', (eb) => eb.selectFrom('outbox_events')
      .select('id')
      .where('processed_at', 'is', null)
      .where('available_at', '<=', sql<Date>`now()`)
      .orderBy('available_at', 'asc')
      .orderBy('id', 'asc')
      .limit(a.limit)
      .forUpdate()
      .skipLocked())
    .returning(OUTBOX_COLUMNS)
    .execute();
}

/** Marks claimed events as dispatched. Only unprocessed rows change, so a repeat is a no-op. */
export async function markOutboxProcessed(db: Executor, ids: string[]) {
  if (ids.length === 0) return [];
  return db.updateTable('outbox_events')
    .set({ processed_at: sql<Date>`now()` })
    .where('id', 'in', ids)
    .where('processed_at', 'is', null)
    .returning(['id'])
    .execute();
}

/** Records a failed dispatch and pushes the event out by retryAfterSeconds. The error text stays on the row. */
export function markOutboxFailed(db: Executor, a: { id: string; error: string; retryAfterSeconds: number }) {
  return db.updateTable('outbox_events')
    .set({
      last_error: a.error,
      available_at: sql<Date>`now() + make_interval(secs => ${a.retryAfterSeconds})`,
    })
    .where('id', '=', a.id)
    .where('processed_at', 'is', null)
    .returning(['id', 'attempts', 'available_at'])
    .executeTakeFirst();
}
